// 소스(src/) → 생성물(dist/).
//   src/skills/<name>.json   스킬 선언 (reads, assets, scripts, profile, commands)
//     → dist/skills/<name>/SKILL.md, references/, assets/, scripts/     (자급자족 번들)
//     → dist/adapters/<runtime>/commands/<cmd>.md                        (명령 어댑터)
//     → dist/adapters/<runtime>/rules/<name>.md                           (경로 조건 규칙: paths + 문서 본문 인라인)
//   src/tools/<name>/SKILL.md (+ references/)
//     → dist/skills/<name>/                                              (코드 패키지가 가진 스킬의 사본)
// 번들 안의 문서 링크는 다시 쓴다: 같은 번들 → references/·assets/·scripts/ 상대 경로,
// 번들 밖의 하네스 파일 → 저장소 URL (경고), 존재하지 않는 대상 → 오류.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const SRC = path.join(root, "src");
export const MARK = "<!-- generated by scripts/build.mjs. Do not edit; edit src/ and rebuild. -->";
const REPO_URL = "https://github.com/rheech22/harness/blob/main/src";

export function parseFrontmatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text);
  if (!m) return { meta: {}, body: text, raw: "" };
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z_]+):\s*(.*)$/.exec(line);
    if (!kv) continue;
    let v = kv[2].trim();
    if (v.startsWith("[") && v.endsWith("]")) v = v.slice(1, -1).split(",").map((s) => s.trim()).filter(Boolean);
    else if (/^".*"$/.test(v)) v = v.slice(1, -1);
    meta[kv[1]] = v;
  }
  return { meta, body: text.slice(m[0].length), raw: m[0] };
}

export function walk(dir, filter = (p) => p.endsWith(".md")) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p, filter) : filter(p) ? [p] : [];
  });
}

export function loadManifests() {
  const dir = path.join(SRC, "skills");
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((n) => n.endsWith(".json")).map((n) => {
    const m = JSON.parse(fs.readFileSync(path.join(dir, n), "utf8"));
    if (m.name !== path.basename(n, ".json")) throw new Error(`src/skills/${n}: name "${m.name}" must match the file name`);
    if (!m.description) throw new Error(`src/skills/${n}: description is required`);
    if (!m.reads?.length) throw new Error(`src/skills/${n}: reads must list at least one doc`);
    return m;
  });
}

export function toolSkillNames() {
  const dir = path.join(SRC, "tools");
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((n) => fs.existsSync(path.join(dir, n, "SKILL.md")));
}

// 번들 하나의 "src 상대경로 → 번들 안 상대경로" 표를 만든다.
function bundleMap(m) {
  const map = new Map();
  for (const r of m.reads) map.set(r, `references/${path.basename(r)}`);
  if (m.profile) map.set(m.profile.default, "references/profile.default.md");
  for (const a of m.assets ?? []) map.set(a, `assets/${path.basename(a)}`);
  for (const s of m.scripts ?? []) map.set(s, `scripts/${path.basename(s)}`);
  return map;
}

// 문서 본문의 상대 링크를 번들 기준으로 다시 쓴다.
function rewriteLinks(text, docRel, map, diag, quiet = false) {
  const docDir = path.posix.dirname(docRel);
  const docOut = map.get(docRel) ?? `references/${path.posix.basename(docRel)}`;
  const outDir = path.posix.dirname(docOut);
  return text.replace(/\]\(([^)\s]+)\)/g, (whole, target) => {
    if (/^(https?:|mailto:|#)/.test(target)) return whole;
    const [p, anchor = ""] = target.split(/(?=#)/);
    const resolved = path.posix.normalize(path.posix.join(docDir, p));
    const inBundle = map.get(resolved);
    if (inBundle) return `](${path.posix.relative(outDir, inBundle) || path.posix.basename(inBundle)}${anchor})`;
    const absSrc = path.join(SRC, resolved);
    const absRoot = path.join(root, path.posix.normalize(path.posix.join("src", docDir, p)));
    if (fs.existsSync(absSrc)) { if (!quiet) diag.warnings.push(`${docRel}: link to ${resolved} is outside the bundle; rewritten to repo URL`); return `](${REPO_URL}/${resolved}${anchor})`; }
    if (fs.existsSync(absRoot)) { if (!quiet) diag.warnings.push(`${docRel}: link to repo root file ${path.relative(root, absRoot)}; rewritten to repo URL`); return `](${REPO_URL.replace(/\/src$/, "")}/${path.relative(root, absRoot)}${anchor})`; }
    diag.errors.push(`${docRel}: unresolved link ${target}`);
    return whole;
  });
}

function renderSkill(m, docs) {
  const domains = [...new Set(docs.flatMap((d) => (Array.isArray(d.meta.domain) ? d.meta.domain : [d.meta.domain ?? "common"])))];
  const lines = [
    "---",
    `name: ${m.name}`,
    `description: "${m.description.replace(/"/g, '\\"')}"`,
    `metadata: { domain: [${domains.join(", ")}], source: docs, generated: true }`,
    "---",
    "",
    MARK,
    "",
    `# ${m.name}`,
    "",
    "Read the bundled references below in full, in order, before acting. Follow them as the source of truth.",
    "",
    ...docs.map((d) => `- \`references/${path.basename(d.rel)}\` — ${d.meta.title ?? path.basename(d.rel, ".md")} (${d.meta.kind ?? "reference"})`),
  ];
  if (m.profile) lines.push("", `## Project profile (do this first)`, "",
    `1. Run \`git rev-parse --show-toplevel\` and read \`<toplevel>/${m.profile.projectPath}\` with the Read tool. Do not guess from memory or directory listings.`,
    `2. If the file exists, it overrides the matching sections of \`references/profile.default.md\`. If it does not exist, use the default for every section.`,
    `3. In your final report state one line: \`Profile: <path or "default">\`, followed by the base ref you used when the profile defines one.`,
    "", `Never edit the default; project values belong in the project file.`);
  if (m.assets?.length) lines.push("", `## Assets`, "", ...m.assets.map((a) => `- \`assets/${path.basename(a)}\``), "", "Paths are relative to this skill's directory.");
  if (m.scripts?.length) lines.push("", `## Scripts`, "", ...m.scripts.map((s) => `- \`scripts/${path.basename(s)}\` — run with \`node <skill-dir>/scripts/${path.basename(s)}\``));
  lines.push("");
  return lines.join("\n");
}

function renderCommand(m, cmd, runtime) {
  if (runtime !== "claude") throw new Error(`${m.name}: unsupported command runtime ${runtime}`);
  return [
    "---",
    `description: ${cmd.description ?? m.description.split(". ")[0] + "."}`,
    ...(cmd.argumentHint ? [`argument-hint: "${cmd.argumentHint}"`] : []),
    "---",
    "",
    MARK,
    "",
    `Load the \`${m.name}\` skill before doing anything else.`,
    "",
    "Request: $ARGUMENTS",
    "",
  ].join("\n");
}

function renderRule(m, rule, runtime, diag) {
  if (runtime !== "claude") throw new Error(`${m.name}: unsupported rule runtime ${runtime}`);
  const reads = rule.reads ?? m.reads;
  const bodies = reads.map((rel) => {
    const abs = path.join(SRC, rel);
    if (!fs.existsSync(abs)) { diag.errors.push(`${m.name}: rule reads ${rel} does not exist`); return ""; }
    const { meta, body } = parseFrontmatter(fs.readFileSync(abs, "utf8"));
    return `<!-- from ${rel} -->\n${rewriteLinks(body.trim(), rel, new Map(), diag, true)}`;
  });
  return ["---", "paths:", ...rule.paths.map((g) => `  - "${g}"`), "---", "", MARK, "",
    `<!-- Path-conditional rule generated from the ${m.name} skill. Loaded when the files above are touched; the full skill is still available on demand. -->`, "",
    ...bodies, ""].join("\n");
}

// 상대경로 → 내용(문자열 또는 Buffer). dist/ 아래에 있어야 할 모든 생성 파일.
export function expected() {
  const out = new Map();
  const diag = { warnings: [], errors: [] };
  const seen = new Set();

  for (const m of loadManifests()) {
    if (seen.has(m.name)) diag.errors.push(`duplicate skill name ${m.name}`); seen.add(m.name);
    const map = bundleMap(m);
    const docs = m.reads.map((rel) => {
      const abs = path.join(SRC, rel);
      if (!fs.existsSync(abs)) { diag.errors.push(`${m.name}: reads ${rel} does not exist`); return null; }
      const text = fs.readFileSync(abs, "utf8");
      return { rel, ...parseFrontmatter(text), text };
    }).filter(Boolean);
    const base = `dist/skills/${m.name}`;
    out.set(`${base}/SKILL.md`, renderSkill(m, docs));
    for (const d of docs) out.set(`${base}/${map.get(d.rel)}`, `${MARK}\n${rewriteLinks(d.text, d.rel, map, diag)}`);
    if (m.profile) {
      const abs = path.join(SRC, m.profile.default);
      if (!fs.existsSync(abs)) diag.errors.push(`${m.name}: profile.default ${m.profile.default} does not exist`);
      else out.set(`${base}/references/profile.default.md`, `${MARK}\n${rewriteLinks(fs.readFileSync(abs, "utf8"), m.profile.default, map, diag)}`);
    }
    for (const rel of [...(m.assets ?? []), ...(m.scripts ?? [])]) {
      const abs = path.join(SRC, rel);
      if (!fs.existsSync(abs)) { diag.errors.push(`${m.name}: ${rel} does not exist`); continue; }
      out.set(`${base}/${map.get(rel)}`, fs.readFileSync(abs));
    }
    for (const [runtime, cmd] of Object.entries(m.commands ?? {})) out.set(`dist/adapters/${runtime}/commands/${cmd.name}.md`, renderCommand(m, cmd, runtime));
    for (const [runtime, rule] of Object.entries(m.rules ?? {})) out.set(`dist/adapters/${runtime}/rules/${rule.name ?? m.name}.md`, renderRule(m, rule, runtime, diag));
  }

  for (const name of toolSkillNames()) {
    if (seen.has(name)) diag.errors.push(`skill name collision: "${name}" is both a docs skill and a tools/ package`); seen.add(name);
    const base = path.join(SRC, "tools", name);
    const skill = fs.readFileSync(path.join(base, "SKILL.md"), "utf8");
    out.set(`dist/skills/${name}/SKILL.md`, skill.replace(/^(---\r?\n[\s\S]*?\r?\n---\r?\n)/, `$1\n${MARK}\n`));
    for (const f of walk(path.join(base, "references"), () => true)) out.set(`dist/skills/${name}/references/${path.relative(path.join(base, "references"), f)}`, fs.readFileSync(f, "utf8"));
  }
  return { files: out, warnings: [...new Set(diag.warnings)], errors: [...new Set(diag.errors)] };
}

export function generatedDirs() {
  const dirs = [];
  const skills = path.join(root, "dist/skills");
  if (fs.existsSync(skills)) for (const n of fs.readdirSync(skills)) { const p = path.join(skills, n, "SKILL.md"); if (fs.existsSync(p) && fs.readFileSync(p, "utf8").includes(MARK)) dirs.push(`dist/skills/${n}`); }
  const adapters = path.join(root, "dist/adapters");
  if (fs.existsSync(adapters)) for (const f of walk(adapters)) if (fs.readFileSync(f, "utf8").includes(MARK)) dirs.push(path.relative(root, f));
  return dirs;
}

const same = (a, b) => Buffer.isBuffer(a) || Buffer.isBuffer(b) ? Buffer.compare(Buffer.from(a), Buffer.from(b)) === 0 : a === b;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { files, warnings, errors } = expected();
  for (const w of warnings) console.log(`warn  ${w}`);
  for (const e of errors) console.log(`error ${e}`);
  if (errors.length) { console.log(`build failed (${errors.length} error(s))`); process.exit(1); }
  const keep = new Set(files.keys());
  for (const rel of generatedDirs()) {
    const isDir = rel.startsWith("dist/skills/");
    const still = isDir ? [...keep].some((k) => k.startsWith(rel + "/")) : keep.has(rel);
    if (!still) { fs.rmSync(path.join(root, rel), { recursive: true }); console.log(`removed stale ${rel}`); }
  }
  // 번들 디렉터리 안의 남은 파일(이전 빌드 산출)도 정리
  for (const rel of [...keep].map((k) => k.split("/").slice(0, 3).join("/")).filter((v, i, a) => v.startsWith("dist/skills/") && a.indexOf(v) === i)) {
    for (const f of walk(path.join(root, rel), () => true)) { const r = path.relative(root, f); if (!keep.has(r)) { fs.rmSync(f); console.log(`removed stale ${r}`); } }
    for (const sub of ["references", "assets", "scripts"]) { const d = path.join(root, rel, sub); if (fs.existsSync(d) && fs.readdirSync(d).length === 0) fs.rmdirSync(d); }
  }
  let wrote = 0;
  for (const [rel, content] of files) {
    const abs = path.join(root, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    if (!fs.existsSync(abs) || !same(fs.readFileSync(abs), content)) { fs.writeFileSync(abs, content); wrote++; }
  }
  const skills = [...new Set([...keep].filter((k) => k.startsWith("dist/skills/")).map((k) => k.split("/")[2]))];
  console.log(`generated ${skills.length} skill(s): ${skills.join(", ")}  (${wrote} file(s) written, ${warnings.length} warning(s))`);
}
